export function getSkillById(id: string) {
  return skills.find((skill) => skill.id === id || skill.slug === id);
}

export function getRelatedSkills(skill: SkillDefinition, limit = 3) {
  const direct = skill.relatedSkillIds
    .map((id) => getSkillById(id))
    .filter((item): item is SkillDefinition => Boolean(item));

  const fallback = skills.filter(
    (item) => item.id !== skill.id && item.markets.some((market) => skill.markets.includes(market)),
  );

  return [...direct, ...fallback.filter((item) => !direct.some((directItem) => directItem.id === item.id))].slice(0, limit);
}

export function getStatusLabel(status: SkillStatus) {
  const labels: Record<SkillStatus, string> = {
    public: "Public Skill",
    verified: "Verified Skill",
    official: "Official Skill",
  };

  return labels[status];
}
